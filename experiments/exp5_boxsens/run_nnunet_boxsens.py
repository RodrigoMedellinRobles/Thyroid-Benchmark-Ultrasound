#!/usr/bin/env python3
"""
In-memory box-prompt sensitivity sweep for a box-conditioned nnU-Net v2 model.

This script loads a trained nnU-Net predictor once, iterates over test cases, and for each
case computes predictions for all box perturbation modes (tight, jitter10, jitter25, shifted,
adversarial). It produces a CSV with metrics directly comparable to the U-Net/TransUNet
box-sensitivity CSVs generated by experiments/exp1_fullsupervised/traditional_boxcond/box_eval.py.

IMPORTANT CAVEAT: the box-conditioned nnU-Net model was trained on TIGHT boxes only (no
train-time jitter), unlike the U-Net/TransUNet models (which saw per-epoch jittered boxes).
This is a documented asymmetry: it affects interpretation of the jitter robustness curve, not
the box-collapse control (a wrong box must still yield a wrong, not box-shaped, prediction).

Key design decisions:
    - All processing happens in memory via nnUNetPredictor.predict_single_npy_array
      (no CLI, no disk re-preprocessing of the test set per mode).
    - The model is initialised once and reused for every image and every mode.
    - Box perturbation and rasterisation reuse thyroidbench/boxes.py verbatim, so the
      box geometry is identical (and seed-matched, seed=42) to the U-Net/TransUNet sweep.
    - Metric definitions replicate experiments/exp1_fullsupervised/traditional_boxcond/eval_nnunet_boxcond.py,
      so the tight-mode DSC reproduces the box-conditioned nnU-Net cell of the
      full-supervision table.
"""

import argparse
import csv
import sys
from datetime import datetime
from pathlib import Path
from typing import Tuple

import numpy as np
import torch
from PIL import Image
from scipy.ndimage import binary_erosion, distance_transform_edt

# --------------------------------------------------------------------------- #
#  Path setup: script lives in experiments/exp5_boxsens/, repo root   #
#  is ../../..                                                                 #
# --------------------------------------------------------------------------- #
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from thyroidbench.boxes import EVAL_BOX_MODES, build_eval_boxes, boxes_to_channel

# --------------------------------------------------------------------------- #
#  Constants & dataset mapping                                                #
# --------------------------------------------------------------------------- #
DATASET_MAP: dict[str, str] = {
    "ddti": "Dataset011_DDTI_boxcond",
    "tn3k": "Dataset012_TN3K_boxcond",
    "thyroidxl": "Dataset013_ThyroidXL_boxcond",
    "stanford_aimi": "Dataset014_StanfordAIMI_boxcond",
}

HD95_INF_CAP: float = float(np.sqrt(2) * 512)


# --------------------------------------------------------------------------- #
#  Helper functions                                                           #
# --------------------------------------------------------------------------- #
def _box_generator(seed: int, mode: str, idx: int) -> torch.Generator:
    """Deterministic generator per (seed, mode, case_index); matches box_eval.py."""
    mode_id = EVAL_BOX_MODES.index(mode)
    s = (seed * 1_000_003 + mode_id * 7_919 + idx) % (2**31 - 1)
    gen = torch.Generator()
    gen.manual_seed(int(s))
    return gen


def _predict(predictor, input_2ch: np.ndarray) -> np.ndarray:
    """Run nnU-Net 2D prediction on a (C, H, W) array.

    nnU-Net 2D expects a pseudo-Z axis: input shape (C, 1, H, W) (matches
    NaturalImage2DIO, which reads each channel as (1, X, Y) and vstacks). We pass
    that shape directly (no broad try/except) so genuine prediction errors are not
    masked. Returns the (H, W) uint8 label map (Z=1 squeezed out).
    """
    input_4d = input_2ch[:, None]  # (C, 1, H, W)
    seg = predictor.predict_single_npy_array(
        input_4d, {"spacing": (999.0, 1.0, 1.0)}, None, None, False
    )
    return np.asarray(seg).squeeze().astype(np.uint8)


def dice_iou(pred: np.ndarray, gt: np.ndarray) -> Tuple[float, float]:
    """Dice and IoU for binary {0,1} masks."""
    inter = (pred * gt).sum()
    dice = 2 * inter / (pred.sum() + gt.sum() + 1e-10)
    iou = inter / (pred.sum() + gt.sum() - inter + 1e-10)
    return float(dice), float(iou)


def hd95(pred: np.ndarray, gt: np.ndarray) -> float:
    """95th-percentile Hausdorff distance; HD95_INF_CAP when exactly one mask is empty."""
    if pred.sum() == 0 and gt.sum() == 0:
        return 0.0
    if pred.sum() == 0 or gt.sum() == 0:
        return HD95_INF_CAP
    pb = pred ^ binary_erosion(pred)
    gb = gt ^ binary_erosion(gt)
    dt_p = distance_transform_edt(~pb.astype(bool))
    dt_g = distance_transform_edt(~gb.astype(bool))
    dists = np.concatenate([dt_g[pb > 0], dt_p[gb > 0]])
    return float(np.percentile(dists, 95))


# --------------------------------------------------------------------------- #
#  Main sweep logic                                                           #
# --------------------------------------------------------------------------- #
def run_sweep(args: argparse.Namespace) -> None:
    """Run the full box-sensitivity sweep for one dataset and save results to CSV."""
    seed = args.seed
    dataset = args.dataset
    modes = list(getattr(args, "modes", None) or EVAL_BOX_MODES)
    out_dir = ROOT / args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    dsname = DATASET_MAP[dataset]
    img_dir = ROOT / f"data/nnunet_raw/{dsname}/imagesTs"
    gt_dir = ROOT / f"data/nnunet_raw/{dsname}/labelsTs"

    # ---- model init (once) ----
    from nnunetv2.inference.predict_from_raw_data import nnUNetPredictor

    predictor = nnUNetPredictor(device=torch.device(args.device), allow_tqdm=False)
    trained_folder = (
        ROOT
        / f"experiments/exp1_fullsupervised/traditional_boxcond/results/nnunet/results/{dsname}"
        / "nnUNetTrainer__nnUNetPlans__2d"
    )
    predictor.initialize_from_trained_model_folder(
        str(trained_folder), use_folds=(0,), checkpoint_name="checkpoint_best.pth"
    )

    # ---- discover test cases ----
    case_stems = sorted(
        p.stem.replace("_0000", "") for p in img_dir.glob("*_0000.png")
    )
    if args.limit > 0:
        case_stems = case_stems[: args.limit]
    n_cases = len(case_stems)
    if n_cases == 0:
        print(f"[WARNING] No test images found in {img_dir}. Bailing out.")
        return

    print(f"Dataset: {dataset} -> {dsname}")
    print(f"Found {n_cases} test images. Sweeping {len(modes)} modes.")

    per_mode_results: dict[str, list[dict]] = {mode: [] for mode in modes}

    for idx, case in enumerate(case_stems):
        img_path = img_dir / f"{case}_0000.png"
        gt_path = gt_dir / f"{case}.png"
        if not img_path.exists() or not gt_path.exists():
            print(f"[SKIP] missing input for case {case}")
            continue

        try:
            image_np = np.array(Image.open(img_path).convert("L"), dtype=np.float32)
            gt_np = (np.array(Image.open(gt_path).convert("L")) > 0).astype(np.uint8)
        except Exception as e:
            print(f"[ERROR] loading {case}: {e}")
            if idx == 0:
                raise
            continue

        H, W = image_np.shape
        gt_torch = torch.from_numpy(gt_np).float().unsqueeze(0).unsqueeze(0)  # (1,1,H,W)

        for mode in modes:
            gen = _box_generator(seed, mode, idx)
            try:
                boxes = build_eval_boxes(gt_torch, mode, H=H, W=W, generator=gen)
                box_chan = boxes_to_channel(boxes, H=H, W=W)  # (1,1,H,W)
                box_np = box_chan[0, 0].cpu().numpy().astype(np.float32)  # (H,W)
                input_2ch = np.stack([image_np, box_np], axis=0).astype(np.float32)
                seg = _predict(predictor, input_2ch)  # (H,W) uint8
            except Exception as e:
                print(f"[ERROR] {case} mode={mode}: {e}")
                if idx == 0:
                    raise
                continue

            model_dice, model_iou = dice_iou(seg, gt_np)
            floor_bin = (box_np > 0.5).astype(np.uint8)
            floor_dice, floor_iou = dice_iou(floor_bin, gt_np)

            per_mode_results[mode].append(
                {
                    "model_dice": model_dice,
                    "model_iou": model_iou,
                    "floor_dice": floor_dice,
                    "floor_iou": floor_iou,
                    "n_fullimage_fallback": 1 if gt_np.sum() == 0 else 0,
                }
            )

        if (idx + 1) % 50 == 0:
            print(f"  processed {idx + 1}/{n_cases} cases ...")

    # ---- aggregate per mode (per-image arithmetic mean) ----
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    csv_rows: list[dict] = []

    print("\n=== Per-mode aggregates ===")
    print(f"{'mode':<14}{'model_dice':<13}{'floor_dice':<13}{'delta_dice':<13}{'n':<6}")
    print("-" * 59)
    for mode in modes:
        recs = per_mode_results[mode]
        if not recs:
            print(f"{mode:<14}(no data)")
            continue
        n_images = len(recs)
        model_dice_mean = float(np.mean([r["model_dice"] for r in recs]))
        model_iou_mean = float(np.mean([r["model_iou"] for r in recs]))
        floor_dice_mean = float(np.mean([r["floor_dice"] for r in recs]))
        floor_iou_mean = float(np.mean([r["floor_iou"] for r in recs]))
        delta_dice = model_dice_mean - floor_dice_mean
        total_fallback = int(np.sum([r["n_fullimage_fallback"] for r in recs]))

        csv_rows.append(
            {
                "dataset": dataset,
                "model": "nnunet_v2",
                "box_conditioned": True,
                "eval_box_mode": mode,
                "model_dice": round(model_dice_mean, 6),
                "model_iou": round(model_iou_mean, 6),
                "floor_dice": round(floor_dice_mean, 6),
                "floor_iou": round(floor_iou_mean, 6),
                "delta_dice": round(delta_dice, 6),
                "n_images": n_images,
                "n_fullimage_fallback": total_fallback,
                "seed": seed,
                "timestamp": timestamp,
            }
        )
        print(
            f"{mode:<14}{model_dice_mean:<13.6f}{floor_dice_mean:<13.6f}"
            f"{delta_dice:<13.6f}{n_images:<6}"
        )

    csv_path = out_dir / f"nnunet_{dataset}_boxcond_boxsens.csv"
    fieldnames = [
        "dataset", "model", "box_conditioned", "eval_box_mode",
        "model_dice", "model_iou", "floor_dice", "floor_iou", "delta_dice",
        "n_images", "n_fullimage_fallback", "seed", "timestamp",
    ]
    # Merge with existing CSV so a single-mode run (--modes jitter50) appends
    # instead of clobbering previously-computed modes.
    new_modes = {r["eval_box_mode"] for r in csv_rows}
    merged: list[dict] = []
    if csv_path.exists():
        with open(csv_path, newline="") as f:
            for old in csv.DictReader(f):
                if old.get("eval_box_mode") not in new_modes:
                    merged.append({c: old.get(c, "") for c in fieldnames})
    merged.extend(csv_rows)
    mode_order = ["tight", "jitter10", "jitter25", "jitter50", "shifted", "adversarial"]
    merged.sort(key=lambda r: mode_order.index(r["eval_box_mode"])
                if r["eval_box_mode"] in mode_order else 99)
    with open(csv_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(merged)
    print(f"\nCSV saved to: {csv_path}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="In-memory box-prompt sensitivity sweep for nnU-Net v2 box-cond model."
    )
    parser.add_argument("--dataset", type=str, required=True, choices=list(DATASET_MAP.keys()))
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--device", type=str, default="cuda")
    parser.add_argument("--limit", type=int, default=0,
                        help="If >0, process only the first N cases (smoke test).")
    parser.add_argument("--out-dir", type=str, default="experiments/exp5_boxsens/results")
    parser.add_argument("--modes", nargs="+", default=list(EVAL_BOX_MODES),
                        choices=list(EVAL_BOX_MODES),
                        help="Perturbation modes to (re)compute; merged into existing CSV.")
    args = parser.parse_args()
    run_sweep(args)


if __name__ == "__main__":
    main()
